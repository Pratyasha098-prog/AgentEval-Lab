# RUN AGENT
# =========================================================

run_clicked = st.button(
    "▶ Run AI Agent",
    type="primary",
    key="run",
    width="stretch"
)

retry_requested = st.session_state.pop("retry_requested", False)

if run_clicked or retry_requested:

    if not user_task.strip():

        st.warning(
            "⚠️ Please enter a user task, or choose an example."
        )

    else:

        try:

            with st.spinner(
                "🧪 Running the demo episode..."
                if mode == DEMO_MODE
                else "🤖 AI agent is processing the task..."
            ):

                result = run_single_episode(
                    user_task,
                    mode=mode
                )

            show_result_source(result["mode"])

            if result["status"] == "needs_clarification":
                show_clarification(result)

            elif result["status"] == "invalid_extraction":
                show_invalid_extraction(result)

            elif result["status"] == "calendar_error":
                show_calendar_error(result)

            else:
                show_success(result)

            if not result.get("log_saved", True):
                st.warning(
                    "⚠️ The trajectory log could not be written for "
                    "this run (the log file is not writable)."
                )

        except DemoTaskNotSupportedError as error:

            st.info(f"🧪 {error}")

            st.write("**Example tasks available in Demo Mode:**")

            for example in DEMO_EXAMPLES:
                st.write(f"• {example['task']}")

        except AgentError as error:

            show_agent_error(error)

        except Exception as error:

            st.error(
                "❌ Agent execution failed unexpectedly."
            )

            with st.expander("Technical details"):
                st.code(
                    f"{type(error).__name__}: {redact_secrets(error)}"
                )

    st.divider()


